static int m10_temperature(int id_uv, int therm_uv, int *dc)
{
 const struct m10_therm_point *table;
 unsigned int count, i;
 long long ohms;
 if (id_uv <= 0 || id_uv >= 1875000)
  return -ENODATA;
 ohms = (long long)id_uv * 100000 / (1875000 - id_uv);
 if (ohms >= 47600 && ohms <= 64400) {
  table = m10_therm_atl;
  count = sizeof(m10_therm_atl) / sizeof(*table);
 } else if (ohms >= 17850 && ohms <= 24150) {
  table = m10_therm_lwn;
  count = sizeof(m10_therm_lwn) / sizeof(*table);
 } else {
  return -ENODATA;
 }
 if (therm_uv > table[0].uv || therm_uv < table[count - 1].uv)
  return -ENODATA;
 for (i = 1; i < count; i++) {
  if (therm_uv >= table[i].uv) {
   *dc = table[i - 1].dc + (long long)(table[i - 1].uv - therm_uv) *
    (table[i].dc - table[i - 1].dc) / (table[i - 1].uv - table[i].uv);
   return 0;
  }
 }
 return -ENODATA;
}
